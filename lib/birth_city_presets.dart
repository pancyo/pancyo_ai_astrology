/// Data-only city presets for birth-place entry.
///
/// Coordinates and IANA time-zone IDs are derived from the principal-location
/// rows in the IANA tzdb `zone1970.tab` file. They are representative city/zone
/// points, not precise street addresses or a geocoder result. The serialized
/// [BirthCityPreset.value] deliberately includes decimal coordinates because
/// the existing SimpleEphemeris resolver already recognizes `lat,lon` text.
library birth_city_presets;

class BirthCityPreset {
  const BirthCityPreset({
    required this.id,
    required this.nameJa,
    required this.nameEn,
    required this.regionJa,
    required this.regionEn,
    required this.countryCode,
    required this.latitude,
    required this.longitude,
    required this.timeZoneId,
    required this.ianaIso6709,
  });

  final String id;
  final String nameJa;
  final String nameEn;
  final String regionJa;
  final String regionEn;
  final String countryCode;
  final double latitude;
  final double longitude;
  final String timeZoneId;

  /// The source coordinate from IANA zone1970.tab, retained for auditability.
  final String ianaIso6709;

  /// Stable stored value. Do not localize or rewrite this value at display time.
  String get value =>
      '$nameEn (${latitude.toStringAsFixed(4)},${longitude.toStringAsFixed(4)})';

  String displayName({required bool english}) => english ? nameEn : nameJa;

  String displayRegion({required bool english}) =>
      english ? regionEn : regionJa;
}

