/// Looks up only the exact serialized value. Unknown/free-text input stays
/// unclassified, so callers can avoid changing the user's time-zone setting.
BirthCityPreset? birthCityPresetForValue(String value) {
  for (final preset in birthCityPresets) {
    if (preset.value == value) return preset;
  }
  return null;
}

