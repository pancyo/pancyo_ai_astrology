/// Applies exactly the existing Japanese quick-chip shortening rule.
String japaneseBirthPlaceShortLabel(String place) {
  if (place == '東京都') return '東京';
  return place
      .replaceFirst(RegExp(r'^北海道'), '')
      .replaceFirst(RegExp(r'^(?:東京都|京都府|大阪府|.{2,3}県)'), '')
      .replaceFirst(RegExp(r'市$'), '');
}

/// Localizes a known Japanese suggestion's visible short label. Unknown input
/// is returned as-is; the user's stored birth-place text is never rewritten.
String birthPlaceEnglishShortLabel(String place) {
  final shortLabel = japaneseBirthPlaceShortLabel(place);
  return japaneseBirthPlaceShortLabelEnglish[shortLabel] ?? place;
}

String birthPlaceEnglishRegionLabel(String region) =>
    japaneseBirthPlaceRegionEnglish[region] ?? region;
